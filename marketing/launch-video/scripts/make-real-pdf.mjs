// Builds the invoice PDF's HTML with the app's own template (src/lib/pdf/htmlTemplate.ts), filled
// with sample data, into src/store/generated/invoiceHtml.ts. The App Store screenshots show it as
// is, so the PDF in them is the app's real output, not a redraw. Run: node scripts/make-real-pdf.mjs
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const outfile = resolve(root, 'node_modules/.cache/htmlTemplate.mjs');

await build({
  entryPoints: [resolve(root, '../../src/lib/pdf/htmlTemplate.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile,
  nodePaths: [resolve(root, 'node_modules')],
  logLevel: 'error',
});
const { buildDocumentHtml } = await import(pathToFileURL(outfile).href);

